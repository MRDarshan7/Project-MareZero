#!/usr/bin/env node
/**
 * queryHorizons.js
 * 
 * Fetches ground-truth topocentric azimuth and elevation from the NASA JPL Horizons REST API.
 * 
 * Target Bodies:
 * - 10: Sun
 * - 399: Earth
 * 
 * Center:
 * - coord@301: Geodetic coordinates on the Moon (body 301)
 * 
 * Quantities:
 * - 4: Apparent topocentric Azimuth & Elevation (Azi, Elev)
 * 
 * Usage:
 *   node scripts/queryHorizons.js
 *   node scripts/queryHorizons.js --update-change4  # replace only this benchmark with live data
 *   node scripts/queryHorizons.js --update-additional  # store Jan 1 / Nov 15, three sites
 */

import { readFile, writeFile } from 'node:fs/promises';

// Native fetch is available in Node 18+

async function fetchHorizons(targetCode, lon, lat, altKm, startTime, stopTime) {
  const params = new URLSearchParams({
    format: 'json',
    COMMAND: `'${targetCode}'`,
    CENTER: `'coord@301'`,
    COORD_TYPE: `'GEODETIC'`,
    SITE_COORD: `'${lon.toFixed(4)},${lat.toFixed(4)},${altKm.toFixed(3)}'`,
    START_TIME: `'${startTime}'`,
    STOP_TIME: `'${stopTime}'`,
    STEP_SIZE: `'1m'`,
    QUANTITIES: `'4'`
  });

  const url = `https://ssd.jpl.nasa.gov/api/horizons.api?${params.toString()}`;
  console.log(`Querying JPL Horizons: Target ${targetCode} (${targetCode === '10' ? 'Sun' : 'Earth'}) at lat=${lat}, lon=${lon}...`);

  const resp = await fetch(url);
  if (!resp.ok) {
    throw new Error(`Horizons HTTP error: ${resp.status} ${resp.statusText}`);
  }

  const data = await resp.json();
  const text = data.result || '';

  // Extract tabular data between $$SOE and $$EOE
  const soeIdx = text.indexOf('$$SOE');
  const eoeIdx = text.indexOf('$$EOE');

  if (soeIdx === -1 || eoeIdx === -1) {
    console.error('Horizons Raw Output:', text.substring(0, 1000));
    throw new Error('Could not parse $$SOE / $$EOE markers from JPL Horizons response');
  }

  const tableBlock = text.substring(soeIdx + 5, eoeIdx).trim();
  const firstLine = tableBlock.split('\n')[0].trim();
  console.log('RAW LINE:', firstLine);
  // Columns: Date__(UT)__HR:MN, flag, Azi_(a-app), Elev_(a-app)
  const tokens = firstLine.split(/\s+/);
  const epoch = tokens.slice(0, 2).join(' ');
  // When flag like *i or m is present, numeric azimuth & elevation are tokens[3], tokens[4]
  // Or grab the last two numeric tokens on the line:
  const lineNumbers = tokens.filter(t => !isNaN(parseFloat(t))).slice(-2).map(parseFloat);
  const azi = lineNumbers[0];
  const elev = lineNumbers[1];
  if (![azi, elev].every(Number.isFinite)) throw new Error('Non-finite Horizons azimuth/elevation');

  return { epoch, azi, elev, rawLine: firstLine, url };
}

function benchmarkRow(site, epochIso, sun, earth, command) {
  return `  {
    // ${site.name}: generated by scripts/queryHorizons.js ${command} from live JPL Horizons.
    // Sun: ${sun.url}
    // Earth: ${earth.url}
    // Raw Sun: ${sun.rawLine}
    // Raw Earth: ${earth.rawLine}
    epochIso: '${epochIso}',
    siteName: ${JSON.stringify(site.name)},
    lat: ${site.lat},
    lon: ${site.lon},
    elevationKm: ${site.altKm},
    expectedSun: { az: ${sun.azi}, el: ${sun.elev}, toleranceDeg: 0.1 },
    expectedEarth: { az: ${earth.azi}, el: ${earth.elev}, toleranceDeg: 0.1 }
  }`;
}

async function main() {
  const sites = [
    { name: 'Shackleton Connecting Ridge', lat: -89.78, lon: 129.2, altKm: 1.35 },
    { name: 'Malapert Massif Peak', lat: -85.99, lon: 2.91, altKm: 5.02 },
    { name: 'Apollo 11', lat: 0.67, lon: 23.47, altKm: -1.40 },
    { name: "Chang'e-4", lat: -45.44, lon: 177.60, altKm: -5.9 }
  ];

  const additional = process.argv.includes('--update-additional');
  if (additional && process.argv.includes('--update-change4')) {
    throw new Error('Use one update option at a time');
  }
  const epochs = additional ? ['2026-01-01T00:00:00.000Z', '2026-11-15T00:00:00.000Z']
    : ['2026-07-03T12:00:00.000Z'];
  const rows = [];
  const benchmarkPath = new URL('../src/ephemeris/horizonsValidation.ts', import.meta.url);

  console.log('================================================================');
  console.log('NASA JPL HORIZONS GROUND-TRUTH QUERY (DE441 Ephemerides)');
  console.log('================================================================\n');

  for (const epochIso of epochs) {
    const startTime = epochIso.slice(0, 16).replace('T', ' ');
    const stopTime = new Date(Date.parse(epochIso) + 60000).toISOString().slice(0, 16).replace('T', ' ');
    console.log(`Epoch: ${startTime} UTC`);
    for (const s of additional ? sites.slice(0, 3) : sites) {
      try {
        const sun = await fetchHorizons('10', s.lon, s.lat, s.altKm, startTime, stopTime);
        const earth = await fetchHorizons('399', s.lon, s.lat, s.altKm, startTime, stopTime);

        console.log(`\nSite: ${s.name} (lat=${s.lat}°, lon=${s.lon}°, alt=${s.altKm} km)`);
        console.log(`  Sun:   Azimuth = ${sun.azi.toFixed(2)}°, Elevation = ${sun.elev.toFixed(2)}°`);
        console.log(`  Earth: Azimuth = ${earth.azi.toFixed(2)}°, Elevation = ${earth.elev.toFixed(2)}°`);

        if (additional) {
          rows.push(benchmarkRow(s, epochIso, sun, earth, '--update-additional'));
        } else if (s.name === "Chang'e-4" && process.argv.includes('--update-change4')) {
          const original = await readFile(benchmarkPath, 'utf8');
          const row = benchmarkRow(s, epochIso, sun, earth, '--update-change4');
          const rowPattern = /^  \{\r?\n    \/\/ Chang'e-4:[\s\S]*?^  \}/m;
          // Also accept the original, unverified row's comment for the one-time replacement.
          const originalPattern = /^  \{\r?\n    \/\/ Chang'e-4 Von[\s\S]*?^  \}/m;
          const pattern = rowPattern.test(original) ? rowPattern : originalPattern;
          if (!pattern.test(original)) throw new Error("Could not locate Chang'e-4 benchmark row");
          const generatedRow = original.includes('\r\n') ? row.replace(/\n/g, '\r\n') : row;
          await writeFile(benchmarkPath, original.replace(pattern, () => generatedRow));
          console.log("Updated Chang'e-4 benchmark from live Horizons responses.");
        }
      } catch (err) {
        console.error(`Failed to query site ${s.name}:`, err.message);
        process.exitCode = 1;
      }
    }
  }
  if (additional && !process.exitCode) {
    const original = await readFile(benchmarkPath, 'utf8');
    // Replace only this generated block; retain the original July rows verbatim.
    const withoutAdditional = original.replace(/,\r?\n  \/\/ BEGIN ADDITIONAL HORIZONS[\s\S]*?\/\/ END ADDITIONAL HORIZONS/, '');
    if (!/\r?\n\];\s*$/.test(withoutAdditional)) throw new Error('Benchmark array terminator not found');
    const block = `,\n  // BEGIN ADDITIONAL HORIZONS\n${rows.join(',\n')}\n  // END ADDITIONAL HORIZONS`;
    const generatedBlock = original.includes('\r\n') ? block.replace(/\n/g, '\r\n') : block;
    await writeFile(benchmarkPath, withoutAdditional.replace(/(\r?\n\];\s*)$/, (_, end) => generatedBlock + end));
    console.log(`Stored ${rows.length} additional benchmark rows from live Horizons responses.`);
  }
}

main().catch(err => { console.error(err); process.exitCode = 1; });
